create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default ('NS-' || upper(substr(encode(gen_random_bytes(8),'hex'),1,10))),
  user_id uuid references auth.users(id) on delete set null,
  status text not null default 'pending_payment' check (status in ('pending_payment','paid','preparing','shipped','delivered','cancelled','payment_failed','refunded')),
  payment_status text not null default 'pending' check (payment_status in ('pending','approved','rejected','cancelled','refunded')),
  payment_provider text, payment_reference text,
  currency text not null default 'COP' check (currency='COP'),
  subtotal_cop bigint not null check (subtotal_cop > 0),
  delivery_type text not null check (delivery_type in ('physical','digital','mixed')),
  customer_first_name text not null, customer_last_name text not null,
  customer_email text, customer_phone text not null,
  address text, neighborhood text, city text, department text, postal_code text,
  delivery_reference text, preferred_payment_method text, customer_note text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id integer not null references public.products(id),
  product_name text not null, unit_price_cop bigint not null check (unit_price_cop > 0),
  quantity integer not null check (quantity between 1 and 10),
  line_total_cop bigint generated always as (unit_price_cop * quantity) stored,
  delivery_type text not null check (delivery_type in ('physical','digital')),
  created_at timestamptz not null default now()
);

create index if not exists orders_user_created_idx on public.orders(user_id,created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists order_items_product_idx on public.order_items(product_id);

create or replace function public.handle_new_novashop_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles(id,full_name)
  values(new.id,coalesce(new.raw_user_meta_data ->> 'full_name',''))
  on conflict(id) do nothing;
  return new;
end;
$$;
revoke execute on function public.handle_new_novashop_user() from public,anon,authenticated;
drop trigger if exists on_novashop_auth_user_created on auth.users;
create trigger on_novashop_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_novashop_user();

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products" on public.products
for select to anon,authenticated using(is_active=true);
drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile" on public.profiles
for select to authenticated using((select auth.uid())=id);
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles
for update to authenticated using((select auth.uid())=id) with check((select auth.uid())=id);
drop policy if exists "Users read own orders" on public.orders;
create policy "Users read own orders" on public.orders
for select to authenticated using((select auth.uid())=user_id);
drop policy if exists "Users read own order items" on public.order_items;
create policy "Users read own order items" on public.order_items
for select to authenticated using(exists(
  select 1 from public.orders o where o.id=order_id and o.user_id=(select auth.uid())
));

revoke all on public.profiles from anon;
revoke all on public.orders from anon,authenticated;
revoke all on public.order_items from anon,authenticated;
grant select on public.products to anon,authenticated;
grant select,update on public.profiles to authenticated;
grant select on public.orders,public.order_items to authenticated;

